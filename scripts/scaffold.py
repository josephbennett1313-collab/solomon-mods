#!/usr/bin/env python3
"""Writes the fixed files of each mod from mods.json: manifest, hooks.json, tsconfig, suite.json."""
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
mods = json.load(open(os.path.join(root, 'mods.json')))
for m in mods:
    d = os.path.join(root, 'mods', m['name'])
    os.makedirs(os.path.join(d, '.claude-plugin'), exist_ok=True)
    os.makedirs(os.path.join(d, 'hooks'), exist_ok=True)
    os.makedirs(os.path.join(d, 'types'), exist_ok=True)
    manifest = {'name': m['name'], 'version': m.get('version', '2.0.0'), 'description': f"{m['title']}: {m['what']}",
                'author': {'name': 'Joseph Bennett'}, 'license': 'MIT', 'homepage': 'https://github.com/josephbennett1313-collab/solomon-mods'}
    if os.path.exists(os.path.join(d, 'types', 'index.d.ts')): manifest['types'] = './types/index.d.ts'
    json.dump(manifest, open(os.path.join(d, '.claude-plugin', 'plugin.json'), 'w'), indent=2)
    json.dump({'modules': ['./register.tsx']}, open(os.path.join(d, 'hooks', 'hooks.json'), 'w'), indent=2)
    json.dump({'extends': './.claude-plugin/types/tsconfig.json'}, open(os.path.join(d, 'tsconfig.json'), 'w'), indent=2)
    suite = {k: m[k] for k in ('title', 'what', 'command', 'pane', 'parts') if k in m}
    json.dump(suite, open(os.path.join(d, 'suite.json'), 'w'), indent=2)
    parts = ''.join(f"- `{p['key']}`: {p['label']}\n" for p in m.get('parts', []))
    readme = f"""# {m['title']}

{m['what']}.

Part of [Solomon Mods](https://github.com/josephbennett1313-collab/solomon-mods), a free set of Claude Code mods by Joseph Bennett.

## Install

```
/plugin marketplace add josephbennett1313-collab/solomon-mods
/plugin install {m['name']}@solomon-mods
```

## Use

Commands: {m.get('command') or 'none, it works on its own'}.
{"It opens as a tab beside the chat." if m.get('pane') else "It shows above the prompt or acts in the background."}
Turn it, or any part of it, on or off from the Mods tab (`/mods`).
""" + (f"\n## Parts you can switch off\n\n{parts}" if parts else "") + "\n## Licence\n\nMIT. See the repository's LICENSE and SOURCES.md.\n"
    open(os.path.join(d, 'README.md'), 'w').write(readme)
# The Switchboard's catalogue, generated so it always matches mods.json.
cat = [{k: m.get(k) for k in ('name', 'title', 'what', 'command', 'pane')} | {'parts': m.get('parts', [])} for m in mods]
open(os.path.join(root, 'shared', 'catalog.ts'), 'w').write('// Generated by scripts/scaffold.py from mods.json. Do not edit by hand.\nexport type Part = { key: string; label: string }\nexport type ModInfo = { name: string; title: string; what: string; command: string; pane: boolean; parts: Part[] }\nexport const CATALOG: ModInfo[] = ' + json.dumps(cat, indent=2) + '\n')
print(f'scaffolded {len(mods)} mods')
